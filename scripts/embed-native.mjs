import { readFile, writeFile } from "node:fs/promises";

const source = await readFile(new URL("../native/main.swift", import.meta.url), "utf8");
const path = new URL("../server/native-source.ts", import.meta.url);
const generated = `// Generated by npm run generate. Edit native/main.swift, not this file.\nexport const nativeSource = ${JSON.stringify(source)};\n`;
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== generated) {
    throw new Error("native/main.swift changed; run npm run generate");
  }
} else {
  await writeFile(path, generated);
}
